/**
 * Generates reference docs from the code so they can never drift:
 *   docs/reference/commands.md, docs/reference/presets.md
 * and copies them into the agent skill. Run: npm run docs
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { catalog, commandSchemas } from '../src/core/commands'
import { APP_ROOT } from '../server/config'

type JsonSchema = { type?: string | string[]; enum?: unknown[]; const?: unknown; description?: string; default?: unknown; minimum?: number; maximum?: number; items?: JsonSchema; properties?: Record<string, JsonSchema>; required?: string[]; anyOf?: JsonSchema[]; prefixItems?: JsonSchema[]; additionalProperties?: unknown }

/** Markdown table cells need escaped pipes. */
const ESC_PIPE = String.raw`\|`
const SEP = ` ${ESC_PIPE} `

function typeOf(s: JsonSchema): string {
  if (s.const !== undefined) return `\`${JSON.stringify(s.const)}\``
  if (s.enum) return s.enum.map((v) => `\`${JSON.stringify(v)}\``).join(SEP)
  if (s.anyOf) return s.anyOf.map(typeOf).join(SEP)
  if (s.prefixItems) return `[${s.prefixItems.map(typeOf).join(', ')}]`
  if (s.type === 'array') return `${s.items ? typeOf(s.items) : 'any'}[]`
  if (s.type === 'object' && s.properties) return `{ ${Object.keys(s.properties).join(', ')} }`
  if (s.type === 'object') return 'object'
  return Array.isArray(s.type) ? s.type.join(SEP) : s.type ?? 'any'
}

function range(s: JsonSchema) {
  const parts: string[] = []
  if (s.minimum !== undefined) parts.push(`≥ ${s.minimum}`)
  if (s.maximum !== undefined) parts.push(`≤ ${s.maximum}`)
  if (s.default !== undefined) parts.push(`default \`${JSON.stringify(s.default)}\``)
  return parts.join(', ')
}

function commandsMd() {
  const out = [
    '# Command reference',
    '',
    '> Generated by `npm run docs` from `src/core/commands`. Do not edit by hand.',
    '',
    'Every command is available as: an MCP tool (same name, plus optional `projectId`), `unicali exec <id> <name> \'<json>\'`,',
    '`POST /api/projects/:id/commands {"command","args"}`, and `useEditor.getState().exec(name, args)` in the editor.',
    '',
  ]
  for (const c of commandSchemas()) {
    const schema = c.args as JsonSchema
    out.push(`## \`${c.name}\``, '', `**${c.summary}.** ${c.description}`, '')
    const props = Object.entries(schema.properties ?? {})
    if (!props.length) {
      out.push('_No arguments._', '')
      continue
    }
    out.push('| Arg | Type | Required | Notes |', '|---|---|---|---|')
    for (const [k, v] of props) {
      const notes = [v.description, range(v)].filter(Boolean).join(' — ')
      out.push(`| \`${k}\` | ${typeOf(v)} | ${schema.required?.includes(k) ? 'yes' : ''} | ${notes.replace(/\|/g, ESC_PIPE)} |`)
      if (v.type === 'array' && v.items?.properties) {
        for (const [ik, iv] of Object.entries(v.items.properties)) {
          out.push(`| \`${k}[].${ik}\` | ${typeOf(iv)} | ${v.items.required?.includes(ik) ? 'yes' : ''} | ${[iv.description, range(iv)].filter(Boolean).join(' — ').replace(/\|/g, ESC_PIPE)} |`)
        }
      }
    }
    out.push('')
  }
  return out.join('\n')
}

function presetsMd() {
  const c = catalog()
  const out = ['# Presets, templates and devices', '', '> Generated by `npm run docs`. Do not edit by hand.', '', c.units, '', '## Motion presets', '']
  for (const p of c.presets) {
    out.push(`### \`${p.id}\` — ${p.name}`, '', `${p.description} Target: **${p.target}** · category: ${p.category} · default duration ${p.defaultDuration}s.`, '')
    out.push('| Param | Type | Range / options | Default |', '|---|---|---|---|')
    for (const s of p.params) {
      const r = s.type === 'number' ? `${s.min} … ${s.max}${s.unit ? ` ${s.unit}` : ''}` : s.type === 'select' ? s.options.map((o) => `\`${o.value}\``).join(', ') : 'true / false'
      out.push(`| \`${s.key}\` | ${s.type} | ${r} | \`${JSON.stringify(s.default)}\` |`)
    }
    out.push('')
  }
  out.push('## Templates', '', '| Id | Name | Length | Description |', '|---|---|---|---|')
  for (const t of c.templates) out.push(`| \`${t.id}\` | ${t.name} | ${t.duration}s | ${t.description} |`)
  out.push('', '## Devices', '', '| Id | Name | Finishes |', '|---|---|---|')
  for (const d of c.devices) out.push(`| \`${d.id}\` | ${d.name} | ${d.finishes.map((f) => `\`${f}\``).join(', ')} |`)
  out.push('', '## Eases', '', c.eases.map((e) => `\`${e}\``).join(', '), '', '## Channels (for keyframes)', '')
  out.push(`- Device: ${c.channels.device.map((x) => `\`<deviceId>.${x}\``).join(', ')}`)
  out.push(`- Camera: ${c.channels.camera.map((x) => `\`camera.${x}\``).join(', ')}`)
  out.push('', '## Output formats', '', '| Id | Size |', '|---|---|')
  for (const f of c.formats) out.push(`| \`${f.id}\` | ${f.width}×${f.height} (${f.label}) |`)
  return out.join('\n') + '\n'
}

const files: Record<string, string> = { 'commands.md': commandsMd(), 'presets.md': presetsMd() }
for (const [name, body] of Object.entries(files)) {
  writeFileSync(join(APP_ROOT, 'docs', 'reference', name), body)
  writeFileSync(join(APP_ROOT, '.claude', 'skills', 'unicali-mockups', 'references', name), body)
}
console.log('Generated docs/reference/{commands,presets}.md (+ skill copies)')
